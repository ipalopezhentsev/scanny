class DataType(IntEnum):
    """PTP datatype codes."""

    UNDEFINED = 0x0000
    INT8 = 0x0001
    UINT8 = 0x0002
    INT16 = 0x0003
    UINT16 = 0x0004
    INT32 = 0x0005
    UINT32 = 0x0006
    INT64 = 0x0007
    UINT64 = 0x0008
    INT128 = 0x0009
    UINT128 = 0x000A
    AINT8 = 0x4001
    AUINT8 = 0x4002
    AINT16 = 0x4003
    AUINT16 = 0x4004
    AINT32 = 0x4005
    AUINT32 = 0x4006
    AINT64 = 0x4007
    AUINT64 = 0x4008
    STR = 0xFFFF


#: struct format character and byte width for each scalar datatype.
SCALAR_FORMATS: "dict[int, tuple[str, int]]" = {
    DataType.INT8: ("b", 1),
    DataType.UINT8: ("B", 1),
    DataType.INT16: ("h", 2),
    DataType.UINT16: ("H", 2),
    DataType.INT32: ("i", 4),
    DataType.UINT32: ("I", 4),
    DataType.INT64: ("q", 8),
    DataType.UINT64: ("Q", 8),
}

#: array datatype -> element datatype.
ARRAY_ELEMENT: "dict[int, int]" = {
    DataType.AINT8: DataType.INT8,
    DataType.AUINT8: DataType.UINT8,
    DataType.AINT16: DataType.INT16,
    DataType.AUINT16: DataType.UINT16,
    DataType.AINT32: DataType.INT32,
    DataType.AUINT32: DataType.UINT32,
    DataType.AINT64: DataType.INT64,
    DataType.AUINT64: DataType.UINT64,
}


class FormFlag(IntEnum):
    NONE = 0x00
    RANGE = 0x01
    ENUMERATION = 0x02
