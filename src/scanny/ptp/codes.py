"""PTP operation, response, event, property and datatype codes.

Standard codes come from the PIMA 15740 / PTP specification; the Nikon vendor
codes follow libgphoto2's ``ptp.h``, which remains the most complete public
record of Nikon's extensions.
"""

from __future__ import annotations

from enum import IntEnum


