    GET_OBJECT_HANDLES = 0x1007
    GET_OBJECT_INFO = 0x1008
    GET_OBJECT = 0x1009
    GET_THUMB = 0x100A
    DELETE_OBJECT = 0x100B
    INITIATE_CAPTURE = 0x100E
    GET_DEVICE_PROP_DESC = 0x1014
    GET_DEVICE_PROP_VALUE = 0x1015
    SET_DEVICE_PROP_VALUE = 0x1016
    RESET_DEVICE_PROP_VALUE = 0x1017
    TERMINATE_OPEN_CAPTURE = 0x1018
    INITIATE_OPEN_CAPTURE = 0x101C
    GET_PARTIAL_OBJECT = 0x101B

    # Nikon vendor extensions.
    NIKON_CAPTURE = 0x90C0
    NIKON_AF_DRIVE = 0x90C1
    NIKON_SET_CONTROL_MODE = 0x90C2
    NIKON_DELETE_IMAGE_SDRAM = 0x90C3
    NIKON_GET_LARGE_THUMB = 0x90C4
    NIKON_GET_EVENT = 0x90C7
    NIKON_DEVICE_READY = 0x90C8
    NIKON_GET_VENDOR_PROP_CODES = 0x90CA
    NIKON_AF_CAPTURE_SDRAM = 0x90CB
    NIKON_GET_PICT_CTRL_DATA = 0x90CC
    NIKON_START_LIVE_VIEW = 0x9201
    NIKON_END_LIVE_VIEW = 0x9202
    NIKON_GET_LIVE_VIEW_IMAGE = 0x9203
    NIKON_MF_DRIVE = 0x9204
    NIKON_CHANGE_AF_AREA = 0x9205
    NIKON_AF_DRIVE_CANCEL = 0x9206
    NIKON_INITIATE_CAPTURE_REC_IN_MEDIA = 0x9207
    NIKON_GET_VENDOR_STORAGE_IDS = 0x9209
    NIKON_START_MOVIE_REC_IN_CARD = 0x920A
    NIKON_END_MOVIE_REC = 0x920B
    NIKON_TERMINATE_CAPTURE = 0x920C
    NIKON_GET_PARTIAL_OBJECT_HI_SPEED = 0x9400


